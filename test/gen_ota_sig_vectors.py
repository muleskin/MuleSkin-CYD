#!/usr/bin/env python3
"""Writes test/ota_sig_vectors.h: a firmware update's signature check, by
someone else's crypto.

    uv run --no-project --with cryptography python test/gen_ota_sig_vectors.py

A THROWAWAY key, made here and thrown away -- not the release key, whose
private half never leaves the server. It signs a made-up "image" the way
tools/sign_firmware.py signs a real one (ECDSA P-256 over the SHA-256, DER),
and test/ota_sig_test.cpp checks that src/ota_sig.cpp -- mbedtls -- agrees:
the good signature passes, and a signature over other bytes, by another key,
cut short or with a byte added does not. Python's `cryptography` shares no
code with mbedtls, so the two agreeing is the point.
"""
import hashlib
import os

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "ota_sig_vectors.h")

image = bytes((i * 7 + 3) & 0xFF for i in range(4096))      # a made-up firmware image
other = image[:-1] + bytes([image[-1] ^ 1])                  # ...one bit different

key = ec.generate_private_key(ec.SECP256R1())
wrong = ec.generate_private_key(ec.SECP256R1())
point = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
wrong_point = wrong.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
sig = key.sign(image, ec.ECDSA(hashes.SHA256()))             # DER, like sign_firmware.py
sig_other = key.sign(other, ec.ECDSA(hashes.SHA256()))


def arr(name, b, ctype="uint8_t"):
    rows = [", ".join("0x%02x" % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return "static const %s %s[%d] = {\n    %s,\n};" % (ctype, name, len(b), ",\n    ".join(rows))


lines = [
    "// Generated by test/gen_ota_sig_vectors.py -- do not edit. A throwaway key.",
    "#pragma once",
    "#include <stdint.h>",
    "",
    "// The image is (i * 7 + 3) & 0xFF for i in 0..4095; IMAGE_SHA its SHA-256.",
    "static const unsigned IMAGE_LEN = 4096;",
    arr("IMAGE_SHA", hashlib.sha256(image).digest()),
    arr("OTHER_SHA", hashlib.sha256(other).digest()),
    "static const unsigned char KEY[1][65] = { {",
    "    " + ", ".join("0x%02x" % x for x in point) + " } };",
    "static const unsigned char WRONG_KEY[1][65] = { {",
    "    " + ", ".join("0x%02x" % x for x in wrong_point) + " } };",
    arr("SIG", sig),
    arr("SIG_OTHER", sig_other),
    "",
]
with open(OUT, "w", newline="\n") as f:
    f.write("\n".join(lines))
print("wrote", OUT)
